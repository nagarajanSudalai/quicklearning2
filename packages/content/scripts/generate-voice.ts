// Records a natural Indian English voice clip for every line the app speaks:
// each puzzle prompt plus the fixed phrases in src/voice.ts. Only missing clips are
// synthesised, so re-running after adding puzzles is cheap.
//
//   GOOGLE_TTS_API_KEY=... npm run voice -w packages/content
//   options: --voice en-IN-Neural2-A  --rate 0.9  --pitch 1  --sample 5 (record only N lines, to audition)
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { clipKey, fixedLines, speakable } from '../src/voice.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const PUZZLES = join(HERE, '..', 'puzzles');
const MOBILE = join(HERE, '..', '..', '..', 'apps', 'mobile');
const CLIP_DIR = join(MOBILE, 'assets', 'voice');
const MANIFEST = join(MOBILE, 'src', 'lib', 'voice-manifest.ts');

const { values: opt } = parseArgs({
  options: {
    voice: { type: 'string', default: 'en-IN-Neural2-A' },
    rate: { type: 'string', default: '0.9' },
    pitch: { type: 'string', default: '1' },
    sample: { type: 'string' },
  },
});

const key = process.env.GOOGLE_TTS_API_KEY;
if (!key) {
  console.error(`GOOGLE_TTS_API_KEY is not set, so no clips were made. The app keeps using the device voice.

To record clips:
  1. In Google Cloud, enable the "Cloud Text-to-Speech API" and create an API key restricted to it.
  2. Run: GOOGLE_TTS_API_KEY=your-key npm run voice -w packages/content`);
  process.exit(1);
}

const files = (dir: string): string[] =>
  readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? files(join(dir, f)) : f.endsWith('.json') ? [join(dir, f)] : []));

const prompts = files(PUZZLES).flatMap((f) => (JSON.parse(readFileSync(f, 'utf8')) as { prompt: string }[]).map((p) => p.prompt));
let lines = [...new Set([...prompts, ...fixedLines()].map(clipKey))].sort();
if (opt.sample) lines = lines.slice(0, Number(opt.sample));

// The voice settings are part of the name, so changing voice re-records everything.
const settings = `${opt.voice}|${opt.rate}|${opt.pitch}`;
const fileFor = (line: string) => `${createHash('sha1').update(`${settings}|${line}`).digest('hex').slice(0, 12)}.mp3`;

async function synthesize(text: string): Promise<Buffer> {
  const res = await fetch(`https://texttospeech.googleapis.com/v1/text:synthesize?key=${encodeURIComponent(key!)}`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      input: { text: speakable(text) },
      voice: { languageCode: opt.voice!.slice(0, 5), name: opt.voice },
      audioConfig: { audioEncoding: 'MP3', speakingRate: Number(opt.rate), pitch: Number(opt.pitch), sampleRateHertz: 24000 },
    }),
  });
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  const { audioContent } = (await res.json()) as { audioContent: string };
  return Buffer.from(audioContent, 'base64');
}

mkdirSync(CLIP_DIR, { recursive: true });
let made = 0;
for (const line of lines) {
  const out = join(CLIP_DIR, fileFor(line));
  if (existsSync(out)) continue;
  writeFileSync(out, await synthesize(line));
  made++;
  process.stdout.write(`\r${made} new clip(s)…`);
}

// Drop clips no longer used (old voice settings or removed puzzles), unless auditioning a sample.
const wanted = new Set(lines.map(fileFor));
if (!opt.sample) for (const f of readdirSync(CLIP_DIR)) if (f.endsWith('.mp3') && !wanted.has(f)) rmSync(join(CLIP_DIR, f));

const rel = relative(dirname(MANIFEST), CLIP_DIR);
writeFileSync(
  MANIFEST,
  `// GENERATED by packages/content/scripts/generate-voice.ts — do not edit by hand.
// Maps each spoken line to its pre-recorded clip. Lines not listed fall back to the device voice.
export const VOICE = ${JSON.stringify(settings)} as string | null;
export const CLIPS: Record<string, number> = {
${lines.map((l) => `  ${JSON.stringify(l)}: require('${rel}/${fileFor(l)}'),`).join('\n')}
};
`,
);
console.log(`\nDone: ${made} new, ${lines.length} total clips. Manifest: ${relative(process.cwd(), MANIFEST)}`);
